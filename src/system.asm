%macro Trap_Desc 3
	dw %1  ; handler_address_low
	dw %2  ; selector
	db 0   ; zero
	db %3  ; attributes
	dw 0   ; handler_address_high
%endmacro

align 16
IDT:
	%rep 256
	Trap_Desc empty_interrupt_handler, 8, 0x8E
	%endrep
	

IDT_pointer:
	dw $ - IDT ;размер
	dd IDT     ;адрес


use32
empty_interrupt_handler:
	pusha
	mov AL, 0x20
	out 0x20, AL
	out 0xA0, AL
	popa
	iret



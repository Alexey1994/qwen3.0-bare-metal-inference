use32
switch_to_16_bits:
	cli

	pop dword [saved_EIP]
	mov [saved_ESP], ESP
	;xor ESP, ESP
	
	lidt [idtr_16]

	mov AX, 32
	mov DS, AX
	mov SS, AX
	mov ES, AX
	mov FS, AX
	mov GS, AX

	jmp 24:p_16_bit
	
	align 16
	use16
	p_16_bit:

	mov EAX, CR0
	and EAX, 0xFFFFFFFE
	mov CR0, EAX

	jmp 0:r_16_bit
	
	r_16_bit:
	mov AX, CS
	mov DS, AX
	mov SS, AX
	mov ES, AX
	mov FS, AX
	mov GS, AX
	
	;mov SP, 0x1000
	;push word [saved_EIP]

	pop AX
	;pop BX
	;push AX
	
	mov BX, 0x0870
	call reset_pic

	sti
	ret



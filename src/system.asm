use16
switch_to_32_bits:
	cli

	mov BX, 0x2028
	call reset_pic
	
	lidt [IDT_pointer]

	mov EAX, CR0
	or EAX, 1
	mov CR0, EAX
	
	jmp 8:setup_32_bit_segment_registers

	use32
	setup_32_bit_segment_registers:
	mov EAX, 16
	mov DS, EAX
	mov SS, EAX
	mov ES, EAX
	mov FS, EAX
	mov GS, EAX
	
	xor EAX, EAX
	pop AX
	mov ESP, [saved_ESP]
	push EAX
	
	sti
	ret


%macro out_8 2
	mov AL, %2
	out %1, AL
%endmacro

use16
;BX - PIC setting, 0x0870 for 16 bit, 0x2028 for 32
reset_pic:
	out_8 0x20, 0x11
	out_8 0x21, BH
	out_8 0x21, 0x04
	out_8 0x21, 0x01
	out_8 0x21, 0x00
	
	out_8 0xA0, 0x11
	out_8 0xA1, BL
	out_8 0xA1, 0x02
	out_8 0xA1, 0x01
	out_8 0xA1, 0x00
	ret


